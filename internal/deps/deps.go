// Package deps materializes the source-visibility side of the component
// contract (plans/implementation.md phase 3):
//
//   - deps/ symlinks: manifest "deps" entries become relative symlinks under
//     <component>/deps/, so a shell in one component can see (and edit) its
//     dependency components. The manifest is the source of truth; this
//     package reconciles the links and never touches non-symlink files.
//   - go.work: a generated workspace file at the root listing every Go
//     component module (plus the buxon SDK), so any shell and any gopls sees
//     the whole workspace. Marker-guarded: hand-edited files are left alone.
package deps

import (
	"fmt"
	"log/slog"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/magik6k/buxon/internal/registry"
	"github.com/magik6k/buxon/internal/util"
)

const workMarker = "// Code generated by buxond; DO NOT EDIT (remove this line to take ownership)."

// Reconcile brings every component's deps/ directory in line with its
// manifest. Returns human-readable problems for bx doctor.
func Reconcile(reg *registry.Registry) []string {
	var problems []string
	for _, c := range reg.Components() {
		if len(c.Manifest.Deps) == 0 {
			// Clean up a now-empty managed dir (symlinks only).
			cleanStale(c, nil)
			continue
		}
		want := map[string]string{} // link name → workspace-relative target
		for _, d := range c.Manifest.Deps {
			if !util.ComponentPathOK(d) {
				problems = append(problems, fmt.Sprintf("%s: dep %q is not a valid component path", c.Path, d))
				continue
			}
			if _, ok := reg.Component(d); !ok {
				problems = append(problems, fmt.Sprintf("%s: dep %q does not exist (yet)", c.Path, d))
			}
			want[filepath.Base(d)] = d
		}

		depDir := filepath.Join(c.Dir, "deps")
		if len(want) > 0 {
			if err := os.MkdirAll(depDir, 0o755); err != nil {
				problems = append(problems, fmt.Sprintf("%s: %v", c.Path, err))
				continue
			}
		}
		for name, target := range want {
			link := filepath.Join(depDir, name)
			// Relative target keeps the workspace relocatable.
			rel, err := filepath.Rel(filepath.Dir(link), filepath.Join(reg.Root, filepath.FromSlash(target)))
			if err != nil {
				continue
			}
			cur, err := os.Readlink(link)
			if err == nil && cur == rel {
				continue
			}
			if err == nil || os.IsNotExist(statErr(link)) {
				_ = os.Remove(link)
				if err := os.Symlink(rel, link); err != nil {
					problems = append(problems, fmt.Sprintf("%s: link %s: %v", c.Path, name, err))
				}
			} else {
				// A real file/dir is squatting on the name: user data, do not touch.
				problems = append(problems, fmt.Sprintf("%s: deps/%s exists and is not a symlink; not touching it", c.Path, name))
			}
		}
		cleanStale(c, want)
	}
	return problems
}

func statErr(p string) error {
	_, err := os.Lstat(p)
	return err
}

// cleanStale removes managed symlinks that are no longer declared.
func cleanStale(c *registry.Component, want map[string]string) {
	depDir := filepath.Join(c.Dir, "deps")
	entries, err := os.ReadDir(depDir)
	if err != nil {
		return
	}
	for _, e := range entries {
		if want != nil {
			if _, ok := want[e.Name()]; ok {
				continue
			}
		}
		p := filepath.Join(depDir, e.Name())
		if fi, err := os.Lstat(p); err == nil && fi.Mode()&os.ModeSymlink != 0 {
			_ = os.Remove(p)
		}
	}
	// Remove the dir itself if now empty.
	if rest, err := os.ReadDir(depDir); err == nil && len(rest) == 0 {
		_ = os.Remove(depDir)
	}
}

// GoWork (re)generates <root>/go.work. sdkPath optionally adds the buxon SDK
// module (BUXON_SDK_PATH / /opt/buxon/sdk in the container image).
func GoWork(reg *registry.Registry, sdkPath string) error {
	var mods []string
	for _, c := range reg.Components() {
		if _, err := os.Stat(filepath.Join(c.Dir, "go.mod")); err == nil {
			mods = append(mods, "./"+c.Path)
		}
	}
	workPath := filepath.Join(reg.Root, "go.work")
	if len(mods) == 0 && sdkPath == "" {
		return nil // nothing Go in the workspace; leave whatever exists alone
	}
	if b, err := os.ReadFile(workPath); err == nil {
		if !strings.Contains(string(b), workMarker) {
			slog.Debug("go.work is hand-managed; not regenerating")
			return nil
		}
	}
	sort.Strings(mods)
	var sb strings.Builder
	sb.WriteString(workMarker + "\n\ngo 1.24\n\nuse (\n")
	for _, m := range mods {
		fmt.Fprintf(&sb, "\t%s\n", m)
	}
	sb.WriteString(")\n")
	if sdkPath != "" {
		// A replace (not a use): workspace `use` doesn't cover unpruned
		// module-graph loads — a dependency with a pre-1.17 go.mod makes
		// `go build` try to fetch the sdk's go.mod from the internet.
		// An all-versions replace resolves it locally in every case.
		fmt.Fprintf(&sb, "\nreplace github.com/magik6k/buxon/sdk => %s\n", sdkPath)
	}

	// Only rewrite on change (avoid feeding the file watcher).
	if cur, err := os.ReadFile(workPath); err == nil && string(cur) == sb.String() {
		return nil
	}
	return os.WriteFile(workPath, []byte(sb.String()), 0o644)
}

// SDKPath locates the buxon Go SDK for go.work generation.
func SDKPath() string {
	if p := os.Getenv("BUXON_SDK_PATH"); p != "" {
		return p
	}
	if _, err := os.Stat("/opt/buxon/sdk/go.mod"); err == nil {
		return "/opt/buxon/sdk"
	}
	return ""
}
