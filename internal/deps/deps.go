// Package deps materializes the source-visibility side of the component
// contract (plans/implementation.md phase 3):
//
//   - deps/ symlinks: manifest "deps" entries become relative symlinks under
//     <component>/deps/, so a shell in one component can see (and edit) its
//     dependency components. The manifest is the source of truth; this
//     package reconciles the links and never touches non-symlink files.
//   - go.work: a generated workspace file at the root listing every Go
//     component module (plus the xbin SDK), so any shell and any gopls sees
//     the whole workspace. Marker-guarded: hand-edited files are left alone.
package deps

import (
	"fmt"
	"log/slog"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/xbin-dev/xbin/internal/registry"
	"github.com/xbin-dev/xbin/internal/util"
)

const workMarker = "// Code generated by xbind; DO NOT EDIT (remove this line to take ownership)."

// Reconcile brings every component's deps/ directory in line with its
// manifest. Returns human-readable problems for bx doctor.
func Reconcile(reg *registry.Registry) []string {
	var problems []string
	for _, c := range reg.Components() {
		if len(c.Manifest.Deps) == 0 {
			// Clean up a now-empty managed dir (symlinks only).
			cleanStale(c, nil)
			continue
		}
		want := map[string]string{} // link name → workspace-relative target
		for _, d := range c.Manifest.Deps {
			if !util.ComponentPathOK(d) {
				problems = append(problems, fmt.Sprintf("%s: dep %q is not a valid component path", c.Path, d))
				continue
			}
			if _, ok := reg.Component(d); !ok {
				problems = append(problems, fmt.Sprintf("%s: dep %q does not exist (yet)", c.Path, d))
			}
			want[filepath.Base(d)] = d
		}

		depDir := filepath.Join(c.Dir, "deps")
		if len(want) > 0 {
			if err := os.MkdirAll(depDir, 0o755); err != nil {
				problems = append(problems, fmt.Sprintf("%s: %v", c.Path, err))
				continue
			}
		}
		for name, target := range want {
			link := filepath.Join(depDir, name)
			// Relative target keeps the workspace relocatable.
			rel, err := filepath.Rel(filepath.Dir(link), filepath.Join(reg.Root, filepath.FromSlash(target)))
			if err != nil {
				continue
			}
			cur, err := os.Readlink(link)
			if err == nil && cur == rel {
				continue
			}
			if err == nil || os.IsNotExist(statErr(link)) {
				_ = os.Remove(link)
				if err := os.Symlink(rel, link); err != nil {
					problems = append(problems, fmt.Sprintf("%s: link %s: %v", c.Path, name, err))
				}
			} else {
				// A real file/dir is squatting on the name: user data, do not touch.
				problems = append(problems, fmt.Sprintf("%s: deps/%s exists and is not a symlink; not touching it", c.Path, name))
			}
		}
		cleanStale(c, want)
	}
	return problems
}

func statErr(p string) error {
	_, err := os.Lstat(p)
	return err
}

// cleanStale removes managed symlinks that are no longer declared.
func cleanStale(c *registry.Component, want map[string]string) {
	depDir := filepath.Join(c.Dir, "deps")
	entries, err := os.ReadDir(depDir)
	if err != nil {
		return
	}
	for _, e := range entries {
		if want != nil {
			if _, ok := want[e.Name()]; ok {
				continue
			}
		}
		p := filepath.Join(depDir, e.Name())
		if fi, err := os.Lstat(p); err == nil && fi.Mode()&os.ModeSymlink != 0 {
			_ = os.Remove(p)
		}
	}
	// Remove the dir itself if now empty.
	if rest, err := os.ReadDir(depDir); err == nil && len(rest) == 0 {
		_ = os.Remove(depDir)
	}
}

// GoWork (re)generates <root>/go.work. sdkPath optionally adds the xbin SDK
// module (XBIN_SDK_PATH / /opt/xbin/sdk in the container image).
//
// A go.work without our marker is treated as hand-managed and left alone — but
// ONLY while it already lists every component's Go module. If a component's
// module is missing (e.g. a `go work use …`, which the go toolchain itself
// suggests in build errors, rewrote the file and stripped our marker), the file
// is stale and would break builds, so we reclaim it. This keeps go.work
// self-healing against the toolchain editing it out from under us.
func GoWork(reg *registry.Registry, sdkPath string) error {
	mods := goModules(reg, nil)
	workPath := filepath.Join(reg.Root, "go.work")
	if len(mods) == 0 && sdkPath == "" {
		return nil // nothing Go in the workspace; leave whatever exists alone
	}
	desired := renderGoWork(mods, sdkPath)

	cur, err := os.ReadFile(workPath)
	if err != nil {
		return os.WriteFile(workPath, []byte(desired), 0o644) // no file yet
	}
	if string(cur) == desired {
		return nil // already correct — don't feed the file watcher
	}
	if !strings.Contains(string(cur), workMarker) {
		if missing := missingModules(string(cur), mods); len(missing) == 0 {
			slog.Debug("go.work is hand-managed and complete; not regenerating")
			return nil
		} else {
			slog.Warn("go.work is missing component modules — reclaiming it (a `go work use` likely rewrote it and stripped xbind's marker)", "missing", missing)
		}
	}
	return os.WriteFile(workPath, []byte(desired), 0o644)
}

// goModules lists the workspace's Go module use-paths, sorted; include
// (nil = all) filters by component path.
func goModules(reg *registry.Registry, include func(path string) bool) []string {
	var mods []string
	for _, c := range reg.Components() {
		if include != nil && !include(c.Path) {
			continue
		}
		switch {
		case fileExists(filepath.Join(c.Dir, "go.mod")):
			mods = append(mods, "./"+c.Path) // canonical: module at the component root
		case fileExists(filepath.Join(c.Dir, "backend", "go.mod")):
			mods = append(mods, "./"+c.Path+"/backend") // module in backend/ (also supported)
		}
	}
	sort.Strings(mods)
	return mods
}

// GoWorkFor renders a go.work covering only the components include admits —
// the content a RESTRICTED terminal's view stages (D40): a full go.work would
// both leak unreadable tiles' names and break `go build` by using directories
// that don't exist in the allow-list mount. "" when there is nothing Go to
// declare.
func GoWorkFor(reg *registry.Registry, sdkPath string, include func(path string) bool) string {
	mods := goModules(reg, include)
	if len(mods) == 0 && sdkPath == "" {
		return ""
	}
	return renderGoWork(mods, sdkPath)
}

func renderGoWork(mods []string, sdkPath string) string {
	var sb strings.Builder
	sb.WriteString(workMarker + "\n\ngo 1.24\n\nuse (\n")
	for _, m := range mods {
		fmt.Fprintf(&sb, "\t%s\n", m)
	}
	sb.WriteString(")\n")
	if sdkPath != "" {
		// A replace (not a use): workspace `use` doesn't cover unpruned
		// module-graph loads — a dependency with a pre-1.17 go.mod makes
		// `go build` try to fetch the sdk's go.mod from the internet.
		// An all-versions replace resolves it locally in every case.
		fmt.Fprintf(&sb, "\nreplace github.com/xbin-dev/xbin/sdk => %s\n", sdkPath)
	}
	return sb.String()
}

// missingModules returns the wanted `use` paths not referenced by an existing
// go.work (matching with or without a leading "./", so it recognises entries
// written by the go toolchain, which omits it).
func missingModules(content string, want []string) []string {
	have := map[string]bool{}
	for _, line := range strings.Split(content, "\n") {
		t := strings.TrimSpace(line)
		t = strings.TrimSpace(strings.TrimPrefix(t, "use "))
		t = strings.TrimSuffix(strings.TrimSpace(strings.TrimPrefix(t, "(")), ")")
		t = strings.TrimSpace(strings.TrimPrefix(strings.TrimSpace(t), "./"))
		if t != "" {
			have[t] = true
		}
	}
	var missing []string
	for _, w := range want {
		if !have[strings.TrimPrefix(w, "./")] {
			missing = append(missing, w)
		}
	}
	return missing
}

func fileExists(p string) bool { _, err := os.Stat(p); return err == nil }

// SDKPath locates the xbin Go SDK for go.work generation.
func SDKPath() string {
	if p := os.Getenv("XBIN_SDK_PATH"); p != "" {
		return p
	}
	if _, err := os.Stat("/opt/xbin/sdk/go.mod"); err == nil {
		return "/opt/xbin/sdk"
	}
	return ""
}
