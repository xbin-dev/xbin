package wire

import (
	"bytes"
	"encoding/hex"
	"encoding/json"
	"os"
	"strings"
	"testing"
)

// vectorsPath is the fixture the sidecar's cargo tests read too
// (sidecar/xbin-iroh/src/{header,control}.rs): the header bytes and the
// control lines exactly as Go writes them. UPDATE_VECTORS=1 rewrites it.
const vectorsPath = "../../../sidecar/xbin-iroh/testdata/wire-vectors.json"

type headerVector struct {
	ALPN     byte   `json:"alpn"`
	Endpoint string `json:"endpoint"`
	Conn     uint64 `json:"conn"`
	Bytes    string `json:"bytes"`
}

type vectors struct {
	Note     string         `json:"note"`
	Headers  []headerVector `json:"headers"`
	Init     []string       `json:"init"`
	Commands []string       `json:"commands"`
	Events   []string       `json:"events"`
}

// sampleEndpoint is bytes 0..31; its hex is what the samples allow.
func sampleEndpoint() (e [32]byte) {
	for i := range e {
		e[i] = byte(i)
	}
	return e
}

func buildVectors(t *testing.T) vectors {
	t.Helper()
	ep := sampleEndpoint()
	var ff [32]byte
	for i := range ff {
		ff[i] = 0xff
	}
	id := hex.EncodeToString(ep[:])
	v := vectors{Note: "generated by internal/apptunnel/wire/vectors_test.go (UPDATE_VECTORS=1); read by the sidecar's cargo tests"}
	for _, h := range []Header{
		{ALPN: ALPNTunnel, Endpoint: ep, Conn: 1},
		{ALPN: ALPNPair, Endpoint: ff, Conn: 0x0102030405060708},
	} {
		v.Headers = append(v.Headers, headerVector{h.ALPN, h.EndpointHex(), h.Conn, hex.EncodeToString(h.Encode())})
	}
	line := func(x any) string {
		b, err := json.Marshal(x)
		if err != nil {
			t.Fatal(err)
		}
		return string(b)
	}
	key := strings.Repeat("a1", 32)
	v.Init = []string{
		line(Init{T: "init", V: 1, SecretKey: key, Relay: Relay{Mode: "custom", URL: "https://relay.example.com", Token: "tok-123"}, Allow: []string{id}, Pairing: true}),
		line(Init{T: "init", V: 1, SecretKey: key, Relay: Relay{Mode: "disabled"}}), // allow: null
		line(Init{T: "init", V: 1, SecretKey: key, Relay: Relay{Mode: "n0"}, Allow: []string{}}),
	}
	v.Commands = []string{
		line(Command{T: "allow", Seq: 7, Allow: []string{id}}),
		line(Command{T: "allow", Seq: 8}), // the empty list: omitted
		line(Command{T: "pairing", Open: true}),
		line(Command{T: "pairing"}),
		line(Command{T: "close", Endpoint: id}),
		line(Command{T: "status"}),
		line(Command{T: "selftest"}),
	}
	v.Events = []string{
		line(Event{T: "ready", EndpointID: id, Ticket: "endpointabc", HomeRelay: "https://relay.example.com/", Version: "0.1.0"}),
		line(Event{T: "ack", Seq: 7}),
		line(Event{T: "status", HomeRelay: "https://relay.example.com/", RelayConnected: true, Conns: []ConnInfo{{Endpoint: id, Conn: 3, Path: "direct", RTTMs: 12}, {Endpoint: id, Conn: 4, Path: "relay"}}}),
		line(Event{T: "status"}),
		line(Event{T: "conn", Endpoint: id, Conn: 3, Open: true, Path: "relay", ALPN: ALPNTunnelName}),
		line(Event{T: "conn", Endpoint: id, Conn: 3}),
		line(Event{T: "reject", Endpoint: id, ALPN: ALPNPairName}),
		line(Event{T: "selftest", Reachable: true, Path: "relay", RTTMs: 40}),
		line(Event{T: "selftest", Error: "timed out"}),
		line(Event{T: "error", Msg: "bind: address in use", Fatal: true}),
	}
	return v
}

// TestVectors pins the fixture the Rust side checks itself against: a Go
// change to the header or a control message that the fixture doesn't carry
// fails here, and the Rust tests then fail until the sidecar follows.
func TestVectors(t *testing.T) {
	want := buildVectors(t)
	b, err := json.MarshalIndent(want, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	b = append(b, '\n')
	if os.Getenv("UPDATE_VECTORS") != "" {
		if err := os.WriteFile(vectorsPath, b, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile(vectorsPath)
	if err != nil {
		t.Fatalf("%v (UPDATE_VECTORS=1 writes it)", err)
	}
	if !bytes.Equal(got, b) {
		t.Fatalf("%s is stale: run UPDATE_VECTORS=1 go test ./internal/apptunnel/wire/", vectorsPath)
	}
	// every line decodes back to what made it
	for _, l := range append(append(append([]string{}, want.Init...), want.Commands...), want.Events...) {
		var m map[string]any
		if err := json.Unmarshal([]byte(l), &m); err != nil || m["t"] == "" {
			t.Errorf("line %s: %v", l, err)
		}
	}
	for _, h := range want.Headers {
		raw, _ := hex.DecodeString(h.Bytes)
		got, err := ParseHeader(raw)
		if err != nil || got.ALPN != h.ALPN || got.EndpointHex() != h.Endpoint || got.Conn != h.Conn {
			t.Errorf("header %s: %+v %v", h.Bytes, got, err)
		}
	}
}
