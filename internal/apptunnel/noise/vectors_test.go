// TestCacophonyVectors runs the Noise community's IK / IKpsk2 vectors
// through the suite this package uses (its X25519 with the low-order check).
func TestCacophonyVectors(t *testing.T) {
	raw, err := os.ReadFile(filepath.Join("testdata", "cacophony.json"))
	if err != nil {
		t.Fatal(err)
	}
	var c struct {
		Vectors []cacoVector `json:"vectors"`
	}
	if err := json.Unmarshal(raw, &c); err != nil || len(c.Vectors) != 2 {
		t.Fatalf("%v %d", err, len(c.Vectors))
	}
	for _, v := range c.Vectors {
		key := func(s string) fnoise.DHKey {
			k, err := KeyFromPrivate(unhex(t, s))
			if err != nil {
				t.Fatal(err)
			}
			return k.dh()
		}
		ic := fnoise.Config{CipherSuite: Suite, Pattern: fnoise.HandshakeIK, Initiator: true, Prologue: unhex(t, v.InitPrologue),
			StaticKeypair: key(v.InitStatic), PeerStatic: unhex(t, v.InitRemoteStatic), Random: bytes.NewReader(unhex(t, v.InitEphemeral))}
		rc := fnoise.Config{CipherSuite: Suite, Pattern: fnoise.HandshakeIK, Prologue: unhex(t, v.RespPrologue),
			StaticKeypair: key(v.RespStatic), Random: bytes.NewReader(unhex(t, v.RespEphemeral))}
		if len(v.InitPSKs) > 0 {
			ic.PresharedKey, ic.PresharedKeyPlacement = unhex(t, v.InitPSKs[0]), 2
			rc.PresharedKey, rc.PresharedKeyPlacement = unhex(t, v.RespPSKs[0]), 2
		}
		ini, err := fnoise.NewHandshakeState(ic)
		if err != nil {
			t.Fatal(err)
		}
		res, _ := fnoise.NewHandshakeState(rc)
		if "Noise_"+fnoise.HandshakeIK.Name+map[bool]string{true: "psk2"}[len(v.InitPSKs) > 0]+"_25519_ChaChaPoly_SHA256" != v.Protocol {
			t.Fatalf("protocol %s", v.Protocol)
		}
		var isend, irecv, rsend, rrecv *fnoise.CipherState
		for i, m := range v.Messages {
			pl, ct := unhex(t, m.Payload), unhex(t, m.Ciphertext)
			var got []byte
			switch {
			case i == 0:
				got, _, _, err = ini.WriteMessage(nil, pl)
				if err == nil {
					_, _, _, err = res.ReadMessage(nil, got)
				}
			case i == 1:
				got, rrecv, rsend, err = res.WriteMessage(nil, pl)
				if err == nil {
					_, isend, irecv, err = ini.ReadMessage(nil, got)
				}
			case i%2 == 0:
				got, err = isend.Encrypt(nil, nil, pl)
				if err == nil {
					_, err = rrecv.Decrypt(nil, nil, got)
				}
			default:
				got, err = rsend.Encrypt(nil, nil, pl)
				if err == nil {
					_, err = irecv.Decrypt(nil, nil, got)
				}
			}
			if err != nil || !bytes.Equal(got, ct) {
				t.Fatalf("%s message %d: %v\n got %x\nwant %x", v.Protocol, i, err, got, ct)
			}
			if i == 1 && h(ini.ChannelBinding()) != v.HandshakeHash {
				t.Fatalf("%s: handshake hash", v.Protocol)
			}
		}
	}
}
